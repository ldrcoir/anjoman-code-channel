def flex(s: str) -> str:
    """هر ZWNJ در الگو به [\u200c]? تبدیل می‌شود تا همیشه مطابق شود."""
    return "".join("[\u200c]?" if ch == "\u200c" else re.escape(ch) for ch in s)

def rep(txt, needle, new, label, count=1, flags=re.S):
    pat = flex(needle)
    n = len(re.findall(pat, txt, flags=flags))
    if n < count:
        # اگر متنِ جدید از قبل هست، مرحله را رد کن
        if flex(new).replace("\\ ", " ") and re.search(flex(new), txt, flags=flags):
            print(f"skip (already applied): {label}")
            return txt
        print(f"!! NOT FOUND ({n}x): {label}"); sys.exit(1)
    out = re.sub(pat, lambda m: new, txt, count=count, flags=flags)
    print(f"ok: {label}")
    return out

