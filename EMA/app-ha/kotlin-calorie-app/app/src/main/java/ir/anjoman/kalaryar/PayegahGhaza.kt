    // فاصله‌ها حفظ می‌شوند تا کلیدواژه‌های فارسیِ چندحرفی هم کار کنند
    fun pakKon(matn: String): String {
        val sb = StringBuilder()
        for (c in matn) {
            when (c) {
                'ي' -> sb.append('ی')
                'ك' -> sb.append('ک')
                'ة', 'ۀ' -> sb.append('ه')
                'أ', 'إ', 'آ' -> sb.append('ا')
                '‌', '\u200f', '\u200e' -> { /* نیم‌فاصله و نشانه‌ها حذف */ }
                else -> sb.append(c.lowercaseChar())
            }
        }
        return sb.toString()
    }

    fun jostOJoo(voroodi: String): List<Ghaza> {
        val pak = pakKon(voroodi)
        if (pak.isEmpty()) return ghazaHa
        val daghigh = ghazaHa.filter { pakKon(it.esm) == pak }
        if (daghigh.isNotEmpty()) return daghigh
        val baEbteda = ghazaHa.filter { pakKon(it.esm).startsWith(pak) }
        if (baEbteda.isNotEmpty()) return baEbteda
        return ghazaHa.filter { pakKon(it.esm).contains(pak) }
    }

    fun baEsm(esm: String): Ghaza? = ghazaHa.firstOrNull { it.esm == esm }
